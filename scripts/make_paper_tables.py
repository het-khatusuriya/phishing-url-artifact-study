"""Build the manuscript tables (Markdown + CSV) from saved results only.

Writes results/tables/paper_T*.csv and results/tables/paper_tables.md.
Every number is read from results/runs/*/metrics.csv, split_*.json,
resources.csv, results/reproduction/*, results/logs/dataset_report_*.json or
results/tables/* produced by the analysis scripts. Missing inputs are
reported as 'pending', never filled in.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results/runs"
T = ROOT / "results/tables"
T.mkdir(parents=True, exist_ok=True)
EXT_LABELLED = ["hannousse2021", "ebbu2017", "phishstorm", "iscx2016", "lineage253k", "phiusiil"]
md = ["# Paper tables (auto-generated)", "",
      "Generated by `scripts/make_paper_tables.py` from files under `results/`. Mean ± sd over seeds unless stated.", ""]


def load(run):
    p = RUNS / run / "metrics.csv"
    return pd.read_csv(p) if p.exists() else None


def ms(x, d=3):
    x = pd.Series(x).dropna()
    if x.empty:
        return "pending"
    return f"{x.mean():.{d}f} ± {x.std(ddof=1):.{d}f}" if len(x) > 1 else f"{x.mean():.{d}f}"


def emit(name, title, df, note=""):
    df.to_csv(T / f"paper_{name}.csv", index=False)
    md.extend([f"## {name}. {title}", "", note, "", df.to_markdown(index=False), ""])


# ---------- T1 datasets ----------
rows = []
for p in sorted((ROOT / "results/logs").glob("dataset_report_*.json")):
    d = json.loads(p.read_text())
    if d["name"].startswith("pool_"):
        continue
    rows.append({"corpus": d["name"], "raw": d["rows_raw"], "kept": d["rows_after_normalisation_dedup"],
                 "malicious": d["positives"], "benign": d["negatives"], "reg_domains": d["unique_registered_domains"],
                 "https": round(d["share_https"], 3), "www": round(d["share_www"], 3),
                 "timestamps": f"{str(d['timestamp_min'])[:7]}→{str(d['timestamp_max'])[:7]}" if d["has_timestamps"] else "no"})
if rows:
    emit("T1", "Corpora after cleaning", pd.DataFrame(rows))

# ---------- T2 original pipeline reproduction ----------
rows = []
orig = pd.read_csv(ROOT / "results/metrics/final_test_metrics.csv")
for _, r in orig.iterrows():
    rows.append({"data": "original raw_data.csv (stored result, not re-run)", "model": r.model, "accuracy": round(r.accuracy, 4),
                 "precision": round(r.precision, 4), "recall": round(r.recall, 4), "f1": round(r.f1_score, 4),
                 "roc_auc": "not stored"})
for ds in ("phiusiil", "lineage253k"):
    p = ROOT / "results/reproduction" / ds / "original_pipeline_metrics.csv"
    if p.exists():
        d = pd.read_csv(p); d = d[d.split == "test"]
        for _, r in d.iterrows():
            rows.append({"data": f"{ds} (original code re-run)", "model": r.model, "accuracy": round(r.accuracy, 4),
                         "precision": round(r.precision, 4), "recall": round(r.recall, 4), "f1": round(r.f1_score, 4),
                         "roc_auc": round(r.roc_auc, 4)})
emit("T2", "Baseline: original pipeline code (random 60/20/20, seed 42, threshold 0.5), test split", pd.DataFrame(rows),
     "Original data are unavailable; the stored numbers are copied from `results/metrics/final_test_metrics.csv` for reference only.")

# ---------- T3 random vs grouped, in-distribution ----------
rows = []
for tag, corpus in (("A", "phiusiil"), ("B", "lineage253k")):
    for fs in ("b28", "v2"):
        for sp in ("random", "grouped"):
            run = f"{tag}_{fs}_{sp}"; m = load(run)
            ov = []
            for sj in sorted((RUNS / run).glob("split_*.json")):
                ov.append(json.loads(sj.read_text())["meta"]["overlap"]["share_test_rows_with_group_in_train"])
            if m is None:
                rows.append({"corpus": corpus, "features": fs, "split": sp, "model": "—", "status": "pending"}); continue
            for model, g in m[(m.eval_set == "test") & (m.policy == "t0.5")].groupby("model"):
                g2 = m[(m.eval_set == "test") & (m.policy == "val_fpr0.01") & (m.model == model)]
                rows.append({"corpus": corpus, "features": fs, "split": sp, "model": model, "seeds": g.seed.nunique(),
                             "test_domain_overlap": ms(ov), "roc_auc": ms(g.roc_auc, 4), "f1@0.5": ms(g.f1, 4),
                             "tpr@valFPR1%": ms(g2.recall, 4), "realised_fpr": ms(g2.fpr, 4)})
emit("T3", "In-distribution test performance: random vs registered-domain-grouped splits", pd.DataFrame(rows))

# ---------- T4 external generalisation by representation ----------
rows = []
for tag in ("A", "B"):
    for run in (f"{tag}_b28_grouped", f"{tag}_b28noart_grouped", f"{tag}_v2_grouped", f"{tag}_v2noart_grouped",
                f"{tag}_v2canon_grouped", f"{tag}_char_grouped"):
        m = load(run)
        if m is None:
            rows.append({"run": run, "status": "pending"}); continue
        for model in sorted(m.model.unique()):
            r = {"run": run, "model": model}
            mm = m[m.model == model]
            r["in-dist AUC"] = ms(mm[(mm.eval_set == "test") & (mm.policy == "t0.5")].roc_auc)
            for e in EXT_LABELLED:
                g = mm[(mm.eval_set == f"external:{e}") & (mm.policy == "val_fpr0.01")]
                if len(g):
                    r[f"{e} AUC"] = ms(g.roc_auc); r[f"{e} FPR"] = ms(g.fpr)
            g = mm[(mm.eval_set == "external:phishtank") & (mm.policy == "val_fpr0.01")]
            r["phishtank recall"] = ms(g.recall) if len(g) else "—"
            rows.append(r)
emit("T4", "External corpora: ROC-AUC and false-positive rate at the validation-chosen FPR≤1 % threshold",
     pd.DataFrame(rows), "FPR = share of the external corpus' benign URLs flagged. PhishTank is positive-only (recall).")

# ---------- T5 leave-one-corpus-out ----------
rows = []
for held in ["phiusiil", "lineage253k", "hannousse2021", "ebbu2017", "phishstorm", "iscx2016"]:
    for rep in ("v2", "v2noart", "v2canon"):
        run = f"LOCO_{held}_{rep}"; m = load(run)
        if m is None:
            rows.append({"held_out": held, "representation": rep, "status": "pending"}); continue
        for model in sorted(m.model.unique()):
            mm = m[m.model == model]
            gi = mm[(mm.eval_set == "test") & (mm.policy == "t0.5")]
            ge = mm[(mm.eval_set == f"external:{held}") & (mm.policy == "val_fpr0.01")]
            g5 = mm[(mm.eval_set == f"external:{held}") & (mm.policy == "t0.5")]
            rows.append({"held_out": held, "representation": rep, "model": model, "pool test AUC": ms(gi.roc_auc),
                         "held-out AUC": ms(ge.roc_auc), "held-out F1@0.5": ms(g5.f1), "held-out recall@valFPR1%": ms(ge.recall),
                         "held-out FPR@valFPR1%": ms(ge.fpr)})
emit("T5", "Leave-one-corpus-out: train on the other five corpora, test on the held-out corpus", pd.DataFrame(rows))

# ---------- T6 paired comparisons ----------
for p in sorted(T.glob("paired_tests_*.csv")):
    pass  # collected below
pt = [pd.read_csv(p) for p in sorted(T.glob("paired_tests_*.csv"))]
if pt:
    d = pd.concat(pt)
    keep = [c for c in ["run_id", "model", "reference", "seed", "roc_auc_delta", "roc_auc_ci_lo", "roc_auc_ci_hi",
                        "f1_delta", "f1_ci_lo", "f1_ci_hi", "mcnemar_p"] if c in d.columns]
    emit("T6", "Paired comparisons against XGBoost on identical test URLs (first seed)", d[keep].round(4))

# ---------- T7 calibration ----------
cal = [pd.read_csv(p) for p in sorted(T.glob("calibration_*.csv"))]
if cal:
    d = pd.concat(cal)
    g = d.groupby(["run_id", "model", "calibration", "eval_set"]).agg(
        ece=("ece", "mean"), brier=("brier", "mean"), recall=("recall_at_val_fpr0.01", "mean"),
        fpr=("fpr_at_val_fpr0.01", "mean")).reset_index().round(4)
    emit("T7", "Calibration (fitted on validation) and FPR≤1 % threshold transfer", g)

# ---------- T8 mutations ----------
mu = [pd.read_csv(p) for p in sorted(T.glob("mutations_*.csv"))]
if mu:
    d = pd.concat(mu)
    emit("T8", "Sensitivity to label-preserving URL variants (test sample)",
         d[["run_id", "model", "mutation", "tier", "share_applicable", "flip_rate", "flip_rate_benign",
            "flip_rate_malicious", "mean_abs_dp", "auc_before", "auc_after"]].round(4))

# ---------- T9 resources ----------
res = [pd.read_csv(p) for p in sorted(RUNS.glob("*/resources.csv"))]
if res:
    d = pd.concat(res)
    d = d[d.run_id.isin(["A_v2canon_grouped", "A_v2_grouped", "A_b28_grouped", "A_char_grouped"])]
    if len(d):
        g = d.groupby(["run_id", "model"]).agg(fit_s=("fit_seconds", "mean"), latency_ms=("predict_latency_ms_per_url", "mean"),
                                               size_mb=("model_size_bytes", lambda x: x.mean() / 1e6),
                                               n_features=("n_features", "first")).reset_index().round(4)
        emit("T9", "Computational cost (test machine: Intel i7-1355U, CPU only)", g,
             "Latency = batch prediction time on the test split divided by its size (includes no feature extraction).")

# ---------- T10 probe ----------
pr = [pd.read_csv(p).assign(file=p.stem) for p in sorted(T.glob("dataset_probe_*.csv"))]
if pr:
    d = pd.concat(pr)
    emit("T10", "Dataset-identification probe (6-way, grouped 5-fold CV, logistic regression)",
         d[["class", "feature_set", "drop_artifacts", "n", "chance", "accuracy", "phiusiil", "lineage253k",
            "hannousse2021", "ebbu2017", "phishstorm", "iscx2016"]].round(3))

(T / "paper_tables.md").write_text("\n".join(md), encoding="utf-8")
print("\n".join(md)[:3000])
